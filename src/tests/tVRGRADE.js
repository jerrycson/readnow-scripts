// 🎯 추천가(판매가치 valueRec) 등급 맞춤 시험 — 정범님 건의 「추천가 잘못된 것들」(11/17) · 노드만
// 상 책인데 첫 페이지 앞자리가 모두 중이고 같은 등급 상은 빨강뿐 → 예전엔 중 매물의 3번째 값 아래로 추천(12,500 · 3,250)
const ML = require('../../readnow-ml-core.js'); let bad = 0; const ok = (c, m) => { if (!c) { bad++; console.log('  ❌', m); } else console.log('  ✓', m); };
const R = (g, p, c) => ({ g, p, c: c || 'green', so: 0 });
const hi = { highDemandBand: 0 };   // 수요 높음 갈래로 보내기(이 시험은 가격 자리만 봄)
// 1) 뇌 과학의 모든 역사 — 중 11,000~20,100 · 최상(믿을 만함) 19,500 · 상은 빨강 21,500~
const brain = [R('중', 11000), R('중', 12000), R('중', 13000), R('중', 14400), R('중', 14400), R('중', 14900), R('중', 17700), R('최상', 19500), R('중', 19500), R('중', 19500), R('중', 20000), R('중', 20100),
  R('상', 21500, 'red'), R('상', 22400, 'red'), R('최상', 22980), R('최상', 25000), R('최상', 25000), R('최상', 25000), R('상', 25900, 'red'), R('최상', 26390)];
let o = ML.valueRec({ grade: '상', sp: 1440, used: 51, list: 33000, rows: brain }, null, hi);
ok(o.strat === 'top3', '수요 높음 갈래: ' + o.strat);
ok(o.price >= 17700 && o.price < 19500, `상 추천가가 중 매물보다 낮지 않고 믿을 만한 최상 19,500보다 아래: ${o.price} (예전 12,500)`);
ok(/더 좋은 등급/.test(o.how) || /우리 등급 이상/.test(o.how), '근거 글에 등급 맞춤이 보임: ' + o.how.slice(0, 120));
// 2) 과학자의 서재 — 중 3,000~6,400 · 상 빨강 5,000~ · 최상(믿을 만함) 6,690
const sci = [R('중', 3000), R('중', 3300), R('중', 3300), R('중', 3500), R('중', 4400), R('중', 4400), R('중', 4400), R('중', 4500), R('상', 5000, 'red'), R('상', 5200, 'red'), R('중', 5500), R('상', 5900, 'red'), R('중', 6400),
  R('최상', 6690), R('최상', 6700), R('상', 6900, 'red'), R('최상', 6990), R('최상', 7000), R('최상', 7400), R('상', 7480, 'red')];
o = ML.valueRec({ grade: '상', sp: 2772, used: 75, list: 15000, rows: sci }, null, hi);
ok(o.price >= 5000 && o.price < 6690, `상 추천가가 믿을 만한 최상 6,690보다 아래이고 중 3번째 3,300보다 훨씬 위: ${o.price} (예전 3,250)`);
// 3) 같은 등급 믿을 만한 매물이 있으면 예전처럼 그 등급 기준 3번째
o = ML.valueRec({ grade: '상', sp: 2000, used: 30, rows: [R('중', 3000), R('상', 5000), R('상', 5200), R('상', 5400), R('최상', 9000)] }, null, hi);
ok(o.price === 5350, '믿을 만한 상 세 개 → 상 3번째 5,400 한 단위 아래 5,350: ' + o.price);
// 4) 등급 글자가 없는 예전 자료 → 예전과 똑같이(첫 페이지 3번째)
o = ML.valueRec({ grade: '상', sp: 2000, used: 30, rows: [{ p: 3000, c: 'green' }, { p: 3300, c: 'green' }, { p: 3600, c: 'green' }, { p: 9000, c: 'green' }] }, null, hi);
ok(o.price === 3550, '등급 없는 줄은 예전 셈(3번째 3,600 → 3,550): ' + o.price);
// 5) 최상 책은 위 등급이 없어 덮개가 걸리지 않음 · 중 책은 최상·상 모두 견줌
o = ML.valueRec({ grade: '최상', sp: 2000, used: 30, rows: [R('중', 3000), R('최상', 8000), R('최상', 8200), R('최상', 8400)] }, null, hi);
ok(o.price === 8350, '최상 책 → 최상 3번째 8,400 → 8,350: ' + o.price);
o = ML.valueRec({ grade: '중', sp: 2000, used: 30, rows: [R('중', 3000), R('중', 3200), R('중', 3400), R('상', 3300), R('최상', 9000)] }, null, hi);
ok(o.price <= 3250, '중 책인데 믿을 만한 상이 3,300 → 그보다 비싸지 않게: ' + o.price);
// 6) 수요 낮음(margin)도 우리 등급 이상 최저가로 — 중 최저가에 맞추지 않음
o = ML.valueRec({ grade: '상', sp: 1, used: 30, rows: [R('중', 3000), R('상', 5000, 'red'), R('최상', 6690)] }, null, { highDemandBand: 99 });
ok(o.price != null && o.price >= 5000 && o.price < 6690, '수요 낮음 · 같은 등급 믿을 만한 매물 없음 → 우리 등급 이상 믿을 만한 최저가(최상 6,690) 한 단위 아래: ' + o.price + ' ' + o.strat);
console.log(bad ? `❌ ${bad}개 실패` : '✅ 모두 통과'); process.exit(bad ? 1 : 0);
